# Image load function
def get_base64_image(image_path):
    if os.path.exists(image_path):
        with open(image_path, "rb") as img_file:
            return base64.b64encode(img_file.read()).decode()
    return ""

def create_pdf_report():
    """PDF generate karne ka function"""
    buffer = io.BytesIO()
    p = canvas.Canvas(buffer, pagesize=letter)
    
    # PDF Content
    p.setFont("Helvetica-Bold", 16)
    p.drawString(100, 750, "RAMEDOX - Equipment Health Report")
    
    p.setFont("Helvetica", 12)
    p.drawString(100, 720, "Date: Oct 20, 2026")
    p.drawString(100, 700, "Generated By: Tech Engineer")
    p.drawString(100, 680, "Total Equipment: 8")
    p.drawString(100, 660, "Operational: 5 | Warning: 2 | Critical: 1")
    
    p.setFont("Helvetica-Bold", 14)
    p.drawString(100, 620, "Equipment Details:")
    
    p.setFont("Helvetica", 10)
    y = 600
    data = [
        "EQ-001 | T-90 Tank | Operational | 92%",
        "EQ-002 | APC Vehicle | Operational | 87%",
        "EQ-003 | Artillery Gun | Maintenance | 65%",
        "EQ-004 | Radar System | Operational | 90%",
        "EQ-005 | Transport Truck | Operational | 88%",
        "EQ-006 | Communication Unit | Critical | 41%",
    ]
    for row in data:
        p.drawString(100, y, row)
        y -= 20
        
    p.showPage()
    p.save()
    buffer.seek(0)
    return buffer

